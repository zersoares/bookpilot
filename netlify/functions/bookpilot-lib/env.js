// Runtime configuration for the BookPilot AI backend.
//
// Every secret is read here and nowhere else, so there is exactly one
// place to audit for "does this value ever reach the browser?". The
// answer is no: nothing in this module is serialised into a response.
//
// Netlify exposes env vars through both `Netlify.env` and `process.env`
// depending on the runtime; read whichever is present.

function read(name) {
  try {
    if (typeof Netlify !== "undefined" && Netlify.env) {
      const v = Netlify.env.get(name);
      if (v) return v;
    }
  } catch {
    /* Netlify global not available (local node, tests) */
  }
  if (typeof process !== "undefined" && process.env && process.env[name]) {
    return process.env[name];
  }
  return "";
}

