// Which capabilities the server can actually deliver right now. The
// client asks for this (via /api/bp/config) and renders "Connect
// integration" or "Demo mode" for anything that is off, instead of
// showing a control that would fail (spec §55).
export function capabilities() {
  return {
    database: Boolean(env.supabaseUrl && env.supabaseAnonKey),
    ai: Boolean(env.anthropicKey),
    billing: Boolean(env.stripeSecret),
    meta: Boolean(env.metaAppId && env.metaAppSecret && env.metaRedirectUri),
    pinterest: Boolean(env.pinterestAppId && env.pinterestAppSecret && env.pinterestRedirectUri),
    tiktok: Boolean(env.tiktokAppId && env.tiktokAppSecret && env.tiktokAuthUrl),
    google: Boolean(env.googleAdsClientId && env.googleAdsClientSecret && env.googleAdsDeveloperToken && env.googleAdsRedirectUri),
    amazon: Boolean(env.amazonAdsClientId && env.amazonAdsClientSecret && env.amazonAdsRedirectUri),
    // Image and video rendering need a media provider that is not wired
    // up yet. Concepts and prompts are generated by the text model; the
    // rendering step is explicitly unavailable rather than faked.
    imageGeneration: false,
    videoGeneration: false,
  };
}

export function requireEnv(...names) {
  const missing = names.filter((n) => !env[n]);
  if (missing.length) {
    const err = new Error(`Missing server configuration: ${missing.join(", ")}`);
    err.code = "server_misconfigured";
    throw err;
  }
}
